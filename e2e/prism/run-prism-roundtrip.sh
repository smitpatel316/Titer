#!/bin/bash
# T-132 — open EVERY Titer-exported file in real Prism 11 on the Mac and
# record per file: CLEAN (loads, no dialog) / WARN (loads after a dialog) /
# FAIL (does not open) / CRASH (Prism process dies opening it).
#
# Runs ON THE MAC, under the Mac slot (see RUNBOOK-MAC.md). Crash-tolerant:
# a Prism crash is recorded and the loop continues (next open relaunches
# Prism). Works on COPIES only — Prism autosaves in place (Nov 18 incident:
# the control file was autosaved over in ~25 min); never open the only copy
# of a fixture. Never Mansi's files (public corpus / Titer exports only).
#
# Input: a list file, one absolute path per line (the files to open).
#   List A (spot-check): 1.6.2 re-exports of the 12 part-3 corpus files —
#     generated by reexport-part3.py (same corpus, same filenames as Nov 17).
#   List B (full): every battery Phase-1 export — the battery lane writes
#     its export list; build it with:
#       find <battery-run-dir> -name '*.prism' -o -name '*.pzfx' | sort > list.txt
# Output: per-file records in <results-dir>/ (<basename>.json + probe dumps),
#   plus a run log. verdict-table.py turns the results dir into the verdict
#   table (same shape as ~/workspace/.helix-prism-gap/part3-verdicts.md).
#
# Usage (on the Mac, from the synced repo dir):
#   bash e2e/prism/run-prism-roundtrip.sh <list-file> [--results-dir DIR] [--copy-dir DIR]
#   --copy-dir: stage a COPY of each file under DIR and open the copy
#     (default: ~/prism-gap/t132-copies). Always on unless --no-copy is given
#     AND the list already points at disposable copies.
#
# Requires: Prism 11 installed (/Applications/Prism 11.app — the app name in
# `open -a` is "Prism 11"), the vendored AppleScripts in e2e/prism/applescript/,
# pgrep, osascript. Licence: Standard Subscription, expires Dec 3, 2026 —
# this run MUST be done by Dec 2.
set -u
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
SCRIPTS="$REPO/e2e/prism/applescript"
LIST="${1:-}"
RESULTS="$HOME/prism-gap/t132-results"
COPYDIR="$HOME/prism-gap/t132-copies"
COPY=1
while [ $# -gt 0 ]; do
  case "$1" in
    --results-dir) RESULTS="$2"; shift 2 ;;
    --copy-dir) COPYDIR="$2"; shift 2 ;;
    --no-copy) COPY=0; shift ;;
    *) [ -z "$LIST" ] && LIST="$1"; shift ;;
  esac
done
[ -n "$LIST" ] && [ -f "$LIST" ] || { echo "FAIL: list file missing: $LIST" >&2; exit 2; }
[ -d "$SCRIPTS" ] || { echo "FAIL: AppleScripts missing: $SCRIPTS" >&2; exit 2; }
mkdir -p "$RESULTS" "$COPYDIR"
LOG="$RESULTS/run.log"
echo "T-132 run started $(date) — list: $LIST" | tee "$LOG"
echo "Prism: $(mdls -name kMDItemVersion "/Applications/Prism 11.app" 2>/dev/null || echo 'version unknown')" | tee -a "$LOG"

# Pre-flight: no stale Prism process holding a crashed state.
if pgrep -x Prism >/dev/null 2>&1; then
  echo "NOTE: Prism already running (PID $(pgrep -x Prism | tr '\n' ' ')) — leaving it; each open reuses it" | tee -a "$LOG"
fi

i=0
while IFS= read -r f; do
  [ -z "$f" ] && continue
  i=$((i+1))
  base=$(basename "$f")
  [ -f "$f" ] || { echo "[$i] SKIP $base — file missing: $f" | tee -a "$LOG"; continue; }
  target="$f"
  if [ "$COPY" = 1 ]; then
    cp "$f" "$COPYDIR/$base" || { echo "[$i] SKIP $base — copy failed" | tee -a "$LOG"; continue; }
    target="$COPYDIR/$base"
  fi
  echo "[$i] OPEN $base $(date +%H:%M:%S)" | tee -a "$LOG"
  rec="$RESULTS/${base}.json"
  # shellcheck disable=SC2094
  {
    echo "{"
    echo "  \"file\": \"$base\","
    echo "  \"source\": \"$f\","
    echo "  \"opened_copy\": \"$target\","
    echo "  \"started\": \"$(date -u +%Y-%m-%dT%H:%M:%SZ)\","
  } > "$rec.tmp"

  open -a "Prism 11" "$target"
  sleep 10
  if ! pgrep -x Prism >/dev/null 2>&1; then
    ips=$(ls -t ~/Library/Logs/DiagnosticReports/Prism-*.ips 2>/dev/null | head -1)
    echo "  CRASH: Prism process died opening $base" | tee -a "$LOG"
    [ -n "$ips" ] && echo "  crash report: $ips" | tee -a "$LOG"
    {
      echo "  \"verdict\": \"CRASH\","
      echo "  \"dialog\": null,"
      echo "  \"crash_report\": \"${ips:-}\","
      echo "  \"doc_title\": null"
      echo "}"
    } >> "$rec.tmp"
    mv "$rec.tmp" "$rec"
    sleep 2
    continue
  fi
  osascript "$SCRIPTS/probe-windows.applescript" > "$RESULTS/${base}.probe1.txt" 2>&1
  dialog="none"
  if grep -q "subrole=\[AXDialog\]" "$RESULTS/${base}.probe1.txt"; then
    if grep -q "BTN: Open" "$RESULTS/${base}.probe1.txt"; then
      dialog="xml-compliance (Open/Cancel)"
      echo "  dialog: compliance -> click Open" | tee -a "$LOG"
      osascript "$SCRIPTS/click-button.applescript" "Open" >> "$RESULTS/${base}.probe1.txt" 2>&1
      sleep 5
    elif grep -q "BTN: OK" "$RESULTS/${base}.probe1.txt"; then
      dialog="info (OK)"
      echo "  dialog: info -> click OK" | tee -a "$LOG"
      osascript "$SCRIPTS/click-button.applescript" "OK" >> "$RESULTS/${base}.probe1.txt" 2>&1
      sleep 5
    else
      dialog="UNEXPECTED — see ${base}.probe1.txt"
      echo "  STOP: unexpected dialog buttons — see ${base}.probe1.txt" | tee -a "$LOG"
      {
        echo "  \"verdict\": \"FAIL\","
        echo "  \"dialog\": \"unexpected\","
        echo "  \"crash_report\": null,"
        echo "  \"doc_title\": null"
        echo "}"
      } >> "$rec.tmp"
      mv "$rec.tmp" "$rec"
      break
    fi
    osascript "$SCRIPTS/probe-windows.applescript" > "$RESULTS/${base}.probe2.txt" 2>&1
  fi
  # Slow-load retry: 0 windows but alive (big files take ~14 s to appear).
  if grep -q "WINDOW COUNT: 0" "$RESULTS/${base}.probe1.txt" && [ ! -f "$RESULTS/${base}.probe2.txt" ]; then
    sleep 6
    osascript "$SCRIPTS/probe-windows.applescript" > "$RESULTS/${base}.probe2.txt" 2>&1
    echo "  (re-probed after slow load)" | tee -a "$LOG"
  fi
  osascript "$SCRIPTS/doc-dump.applescript" > "$RESULTS/${base}.doc.txt" 2>&1
  title=$(head -1 "$RESULTS/${base}.doc.txt" 2>/dev/null | tr -d '\r')
  echo "  doc: $title" | tee -a "$LOG"
  osascript "$SCRIPTS/close-doc-ax.applescript" > "$RESULTS/${base}.close.txt" 2>&1
  if grep -q "CLOSING-WIN" "$RESULTS/${base}.close.txt" || grep -q "ALREADY-CLEAN" "$RESULTS/${base}.close.txt"; then
    echo "  closed clean" | tee -a "$LOG"
    closed="true"
  elif grep -q "WINDOWS-AFTER: Welcome to GraphPad Prism" "$RESULTS/${base}.close.txt"; then
    echo "  closed, welcome-only" | tee -a "$LOG"
    closed="true"
  else
    echo "  STOP: close left unexpected state — see ${base}.close.txt" | tee -a "$LOG"
    closed="false"
    {
      echo "  \"verdict\": \"FAIL\","
      echo "  \"dialog\": \"$dialog\","
      echo "  \"crash_report\": null,"
      echo "  \"doc_title\": \"$title\""
      echo "}"
    } >> "$rec.tmp"
    mv "$rec.tmp" "$rec"
    break
  fi
  if [ "$dialog" = "none" ]; then verdict="CLEAN"; else verdict="WARN"; fi
  {
    echo "  \"verdict\": \"$verdict\","
    echo "  \"dialog\": \"$dialog\","
    echo "  \"crash_report\": null,"
    echo "  \"doc_title\": \"$title\""
    echo "}"
  } >> "$rec.tmp"
  mv "$rec.tmp" "$rec"
  echo "  verdict: $verdict" | tee -a "$LOG"
  sleep 2
done < "$LIST"
echo "DONE $i files $(date +%H:%M:%S)" | tee -a "$LOG"
python3 "$REPO/e2e/prism/verdict-table.py" "$RESULTS" | tee -a "$LOG"
