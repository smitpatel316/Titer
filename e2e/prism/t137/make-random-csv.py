#!/usr/bin/env python3
"""Deterministic random-data CSV for T-137 (Prism-native round-trip sanity).

Generates the raw-data file that the Mac operator imports into real Prism 11
(File > Import, type-ahead route — see t137/RUNBOOK section in README.md)
to build the Prism-native project: one Column table, 10 rows, values that
make the modification unmistakable (the T-137 driver changes one cell to
987654.321, a value that cannot occur in the fixture).

Deterministic (seed 137) so the fixture can be regenerated byte-identically
anywhere; the file itself is public synthetic data, never Mansi's.

Usage:
  python3 t137/make-random-csv.py [--out FILE] [--rows N] [--seed N]
Default out: t137-random-data.csv next to this script.
Columns: Group (A/B alternating), Value (uniform 10.0–99.0, 3 dp).
"""
import argparse
import csv
import random
from pathlib import Path

SENTINEL = 987654.321  # the value t137-titer.py writes into one cell


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(Path(__file__).with_name("t137-random-data.csv")))
    ap.add_argument("--rows", type=int, default=10)
    ap.add_argument("--seed", type=int, default=137)
    args = ap.parse_args()
    rng = random.Random(args.seed)
    rows = [[("A" if i % 2 == 0 else "B"), f"{rng.uniform(10.0, 99.0):.3f}"]
            for i in range(args.rows)]
    # Guard: the sentinel must not occur in the fixture (it cannot — the
    # range is 10–99 — but assert it so a future range change fails loudly).
    assert all(float(v) != SENTINEL for _, v in rows)
    with open(args.out, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["Group", "Value"])
        w.writerows(rows)
    print(f"wrote {args.out} ({args.rows} rows, seed {args.seed})")
    print(f"sentinel for the modify step (must NOT appear above): {SENTINEL}")


if __name__ == "__main__":
    main()
